// Exports the existing GhostJS SECRET_PATTERNS (TypeScript engine) into a
// self-contained Java source file used by the Burp extension.
//
// Single source of truth: the Burp extension never re-types the 150 regexes.
// Run:  node --import tsx export-patterns.mjs
//
// Reads (read-only) from ../TrinetLayer Code/server/ghostjs/secret-patterns.ts
// Writes ./src/main/java/ghostjs/core/GeneratedPatterns.java

import { pathToFileURL } from "node:url";
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const patternsTs = resolve(
  here,
  "../TrinetLayer Code/server/ghostjs/secret-patterns.ts"
);

const mod = await import(pathToFileURL(patternsTs).href);
const patterns = mod.SECRET_PATTERNS;
if (!Array.isArray(patterns) || patterns.length === 0) {
  throw new Error("SECRET_PATTERNS not found or empty");
}

function javaStr(s) {
  if (s === null || s === undefined) return '""';
  let out = "";
  for (const ch of String(s)) {
    const code = ch.codePointAt(0);
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (code < 0x20) out += "\\u" + code.toString(16).padStart(4, "0");
    else out += ch;
  }
  return '"' + out + '"';
}

const rows = patterns.map((p) => {
  const src = p.pattern.source;
  const flags = p.pattern.flags || "";
  return (
    "    new RawPattern(" +
    [
      javaStr(p.name),
      javaStr(p.category),
      javaStr(src),
      javaStr(flags),
      javaStr(p.severity),
      String(p.confidence ?? 0),
      javaStr(p.impactSummary || ""),
      javaStr(p.remediation || ""),
    ].join(", ") +
    ")"
  );
});

const java = `package ghostjs.core;

import java.util.List;

/**
 * AUTO-GENERATED by export-patterns.mjs from the GhostJS TypeScript engine
 * (secret-patterns.ts). DO NOT EDIT BY HAND. Re-run the exporter to refresh.
 *
 * ${patterns.length} secret detection patterns, single source of truth.
 */
public final class GeneratedPatterns {
    private GeneratedPatterns() {}

    public static final List<RawPattern> ALL = List.of(
${rows.join(",\n")}
    );
}
`;

const outPath = resolve(here, "src/main/java/ghostjs/core/GeneratedPatterns.java");
writeFileSync(outPath, java, "utf8");
console.log(`Wrote ${patterns.length} patterns -> ${outPath}`);
